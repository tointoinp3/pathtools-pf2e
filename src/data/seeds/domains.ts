const DOMAINS_BY_ID = Object.fromEntries(
  catalogDomains.map((domain) => [domain.id, domain]),
) as Record<string, DivineDomain>

const DOMAINS_BY_NAME = Object.fromEntries(
  catalogDomains.map((domain) => [domain.originalName.toLowerCase(), domain]),
) as Record<string, DivineDomain>

export function getDomainById(id: string | null | undefined): DivineDomain | null {
  if (!id) return null
  return DOMAINS_BY_ID[id] ?? null
}

export function getDomainByOriginalName(
  name: string | null | undefined,
): DivineDomain | null {
  if (!name) return null
  return DOMAINS_BY_NAME[name.toLowerCase()] ?? null
}
