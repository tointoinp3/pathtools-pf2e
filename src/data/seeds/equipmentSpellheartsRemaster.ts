import { spellheartItem } from './equipmentFactory'
import type { ItemDefinition, SpellheartStats, TalismanHost } from '@/types/equipment'
import { TALISMAN_HOST_LABELS } from '@/types/equipment'

function h(opts: {
  aonId: number
  key?: string
  name: string
  originalName: string
  level: number
  priceGp: number
  page: number
  sourceBook: 'Rage of Elements' | 'Impossible Magic'
  traits?: string[]
  affixesTo: TalismanHost
  flavor: string
  spellAttack?: number
  spellDc?: number
  armorBenefit: string
  weaponBenefit: string
  cantrip: string
  dailySpells?: string[]
}): ItemDefinition {
  const spellheart: SpellheartStats = {
    affixesTo: opts.affixesTo,
    spellAttack: opts.spellAttack,
    spellDc: opts.spellDc,
    armorBenefit: opts.armorBenefit,
    weaponBenefit: opts.weaponBenefit,
    cantrip: opts.cantrip,
    dailySpells: opts.dailySpells,
  }
  const dc = opts.spellDc ? ` CD de magia ${opts.spellDc}.` : ''
  const atk = opts.spellAttack ? ` Ataque de magia +${opts.spellAttack}.` : ''
  const daily = opts.dailySpells?.length
    ? ` 1/dia: ${opts.dailySpells.join('; ')}.`
    : ''
  return spellheartItem({
    id: `spellheart-${opts.aonId}${opts.key ? `-${opts.key}` : ''}`,
    aonId: opts.aonId,
    name: opts.name,
    originalName: opts.originalName,
    level: opts.level,
    priceGp: opts.priceGp,
    page: opts.page,
    sourceBook: opts.sourceBook,
    traits: opts.traits,
    spellheart,
    description: `${opts.flavor} Afixe em ${TALISMAN_HOST_LABELS[opts.affixesTo]} (10 min; no lugar de um talismã, não junto). Não se consome ao ativar.${atk}${dc} Armadura: ${opts.armorBenefit} Arma: ${opts.weaponBenefit} Truque: ${opts.cantrip}.${daily} Use seu ataque de magia ou CD se for maior.`,
  })
}

