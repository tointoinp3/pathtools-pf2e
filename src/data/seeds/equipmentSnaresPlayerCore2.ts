import { snareItem } from './equipmentFactory'
import type { ItemDefinition, SnareStats } from '@/types/equipment'
import type { Rarity } from '@/types/core'

function s(opts: {
  aonId: number
  name: string
  originalName: string
  level: number
  priceGp: number
  page: number
  rarity?: Rarity
  traits?: string[]
  flavor: string
  note: string
  save?: string
  craftRequirement?: string
}): ItemDefinition {
  const snare: SnareStats = {
    note: opts.note,
    save: opts.save,
    craftRequirement: opts.craftRequirement,
  }
  const save = opts.save ? ` ${opts.save}.` : ''
  const craft = opts.craftRequirement
    ? ` Ofício: ${opts.craftRequirement}.`
    : ''
  return snareItem({
    id: `snare-${opts.aonId}`,
    aonId: opts.aonId,
    name: opts.name,
    originalName: opts.originalName,
    level: opts.level,
    priceGp: opts.priceGp,
    page: opts.page,
    rarity: opts.rarity,
    traits: opts.traits,
    snare,
    description: `${opts.flavor} Ocupe um quadrado de 5 pés; uma cilada por quadrado. Criatura Pequena ou maior que entra dispara e consome a cilada.${save} ${opts.note}${craft} Precisa do feito Criar Ciladas e de um kit de ciladas. 1 minuto para armar pagando o preço.`,
  })
}

