function pickFeat(opts: {
  id: string
  name: string
  originalName: string
  level: number
  archetypeId: string
  prereqId: string
  prereqName: string
  description: string
  sourceId: string
  sourcePage: number
  aonUrl: string
  extraPrereq?: Feat['prerequisites']
}): Feat {
  return {
    id: opts.id,
    name: opts.name,
    originalName: opts.originalName,
    level: opts.level,
    category: 'archetype',
    archetypeId: opts.archetypeId,
    traits: ['Arquétipo'],
    rarity: 'common',
    provenance: { type: 'official' },
    description: opts.description,
    prerequisites: [
      { kind: 'feat', featId: opts.prereqId, featName: opts.prereqName },
      ...(opts.extraPrereq ?? []),
    ],
    sourceId: opts.sourceId,
    sourcePage: opts.sourcePage,
    aonUrl: opts.aonUrl,
  }
}

