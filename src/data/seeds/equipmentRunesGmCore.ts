/**
 * Runas — GM Core (Remaster).
 * Só páginas Remaster do Archives of Nethys (Equipment.aspx ID 2785–2854).
 * Variantes da mesma página compartilham o aonId.
 */

function elementalWeapon(opts: {
  aonId: number
  family: string
  name: string
  originalName: string
  shortLabel: string
  greaterName: string
  greaterOriginal: string
  greaterShort: string
  damageType: DamageTypeId
  trait: string
  page: number
  typePt: string
}): ItemDefinition[] {
  const extra = (greater: boolean): RuneStats['extraDamage'] => [
    { dice: '1d6', damageType: opts.damageType, when: 'hit' },
    {
      dice: greater ? '2d10' : '1d10',
      damageType: opts.damageType,
      when: 'crit',
      persistent: true,
    },
  ]
  return [
    runeItem({
      id: `rune-${opts.aonId}`,
      aonId: opts.aonId,
      name: opts.name,
      originalName: opts.originalName,
      level: 8,
      priceGp: 500,
      page: opts.page,
      usage: 'etched-weapon',
      traits: [opts.trait],
      rune: {
        kind: 'property',
        appliesTo: ['weapon'],
        family: opts.family,
        shortLabel: opts.shortLabel,
        extraDamage: extra(false),
      },
      description: `A arma causa +1d6 de dano de ${opts.typePt} no acerto, e +1d10 de dano persistente de ${opts.typePt} no crítico.`,
    }),
    runeItem({
      id: `rune-${opts.aonId}-greater`,
      aonId: opts.aonId,
      name: opts.greaterName,
      originalName: opts.greaterOriginal,
      level: 15,
      priceGp: 6500,
      page: opts.page,
      usage: 'etched-weapon',
      traits: [opts.trait],
      rune: {
        kind: 'property',
        appliesTo: ['weapon'],
        family: opts.family,
        shortLabel: opts.greaterShort,
        extraDamage: extra(true),
      },
      description: `Como a runa ${opts.name.toLowerCase()}, mas o dano persistente no crítico sobe para 2d10. O dano de ${opts.typePt} desta arma ignora a resistência do alvo a ${opts.typePt}.`,
    }),
  ]
}

function energyResist(
  type: 'acid' | 'cold' | 'electricity' | 'fire',
  typePt: string,
  typeCap: string,
): ItemDefinition[] {
  return [
    runeItem({
      id: `rune-2788-${type}`,
      aonId: 2788,
      name: `Resistente a ${typePt}`,
      originalName: `Energy-Resistant (${typeCap})`,
      level: 8,
      priceGp: 420,
      page: 226,
      usage: 'etched-armor',
      rune: {
        kind: 'property',
        appliesTo: ['armor'],
        family: `energy-resist-${type}`,
        shortLabel: `resistente a ${typePt}`,
        energyResistance: { damageType: type, value: 5 },
      },
      description: `Você recebe resistência 5 a ${typePt}. Várias runas deste tipo podem coexistir na mesma armadura, desde que cada uma cubra um tipo de dano diferente.`,
    }),
    runeItem({
      id: `rune-2788-${type}-greater`,
      aonId: 2788,
      name: `Resistente a ${typePt} maior`,
      originalName: `Energy-Resistant (Greater, ${typeCap})`,
      level: 12,
      priceGp: 1650,
      page: 226,
      usage: 'etched-armor',
      rune: {
        kind: 'property',
        appliesTo: ['armor'],
        family: `energy-resist-${type}`,
        shortLabel: `resistente a ${typePt} maior`,
        energyResistance: { damageType: type, value: 10 },
      },
      description: `Você recebe resistência 10 a ${typePt}. Pode coexistir com outras runas resistentes a energia de tipos diferentes.`,
    }),
  ]
}

