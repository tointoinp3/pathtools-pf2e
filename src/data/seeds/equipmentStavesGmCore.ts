import { staffItem } from './equipmentFactory'
import type { ItemDefinition, StaffSpellEntry } from '@/types/equipment'

function sp(rank: number, ...originalNames: string[]): StaffSpellEntry {
  return {
    rank,
    spellNames: originalNames,
    spellIds: originalNames.map(
      (name) =>
        `spell-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`,
    ),
  }
}

function ranks(...entries: StaffSpellEntry[]): StaffSpellEntry[] {
  return entries
}

