const SRC = SOURCE_IMPOSSIBLE_MAGIC_ID

function rune(opts: {
  id: string
  name: string
  originalName: string
  category: 'rune' | 'diacritic'
  level: number
  page: number
  usage?: string
  description: string
  etched: string
  invocation?: string
}): ReturnType<typeof catalogOption> {
  return catalogOption({
    id: opts.id,
    name: opts.name,
    originalName: opts.originalName,
    category: opts.category,
    level: opts.level,
    usage: opts.usage,
    sourcePage: opts.page,
    description: opts.description,
    rulesSummary: opts.invocation
      ? `${opts.etched} Invocação: ${opts.invocation}`
      : opts.etched,
    sections: [
      section(opts.category === 'diacritic' ? 'Sobre a base' : 'No portador', opts.etched),
      ...(opts.invocation
        ? [section('Invocação', opts.invocation)]
        : []),
    ],
  })
}

