import type {
  ActionGroup,
  CombatAction,
  CombatActionCategory,
  CombatActionCost,
} from '@/types/action'

function action(
  id: string,
  name: string,
  originalName: string,
  actionType: CombatActionCost,
  group: ActionGroup,
  description: string,
  extra: {
    category?: CombatActionCategory
    traits?: string[]
    trigger?: string
    requirements?: string
    source?: string
    activityTime?: string
    featRequired?: boolean
    trainedOnly?: boolean
  } = {},
): CombatAction {
  return {
    id,
    name,
    originalName,
    actionType,
    category: extra.category ?? 'skill',
    group,
    traits: extra.traits ?? [],
    description,
    source: extra.source ?? 'Player Core',
    trigger: extra.trigger,
    requirements: extra.requirements,
    activityTime: extra.activityTime,
    featRequired: extra.featRequired,
    trainedOnly: extra.trainedOnly,
  }
}

