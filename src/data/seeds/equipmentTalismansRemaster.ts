import { talismanItem } from './equipmentFactory'
import type { ItemDefinition, TalismanHost, TalismanStats } from '@/types/equipment'
import type { Rarity } from '@/types/core'
import { TALISMAN_HOST_LABELS } from '@/types/equipment'

function t(opts: {
  aonId: number
  key?: string
  name: string
  originalName: string
  level: number
  priceGp: number
  page: number
  sourceBook?: 'GM Core' | 'Player Core 2'
  rarity?: Rarity
  traits?: string[]
  affixesTo: TalismanHost
  activate: string
  trigger?: string
  requirements?: string
  flavor: string
  note: string
  potencyRuneIds?: string[]
  alloyMaterials?: string[]
  maxWeaponLevel?: number | null
}): ItemDefinition {
  const talisman: TalismanStats = {
    affixesTo: opts.affixesTo,
    activate: opts.activate,
    trigger: opts.trigger,
    requirements: opts.requirements,
    note: opts.note,
    potencyRuneIds: opts.potencyRuneIds,
    alloyMaterials: opts.alloyMaterials,
    maxWeaponLevel: opts.maxWeaponLevel,
  }
  const trigger = opts.trigger ? ` Gatilho: ${opts.trigger}.` : ''
  const req = opts.requirements ? ` Requisito: ${opts.requirements}.` : ''
  return talismanItem({
    id: `talisman-${opts.aonId}${opts.key ? `-${opts.key}` : ''}`,
    aonId: opts.aonId,
    name: opts.name,
    originalName: opts.originalName,
    level: opts.level,
    priceGp: opts.priceGp,
    page: opts.page,
    sourceBook: opts.sourceBook,
    rarity: opts.rarity,
    traits: opts.traits,
    talisman,
    description: `${opts.flavor} Afixe em ${TALISMAN_HOST_LABELS[opts.affixesTo]}. Ativação: ${opts.activate}.${trigger}${req} ${opts.note}`,
  })
}

