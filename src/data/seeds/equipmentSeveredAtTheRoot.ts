function staffSpells(
  entries: Array<[rank: number, ...names: string[]]>,
): StaffSpellEntry[] {
  return entries.map(([rank, ...spellNames]) => ({
    rank,
    spellNames,
    spellIds: spellNames.map(
      (name) =>
        `spell-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`,
    ),
  }))
}

