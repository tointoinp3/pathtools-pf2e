import { grimoireItem } from './equipmentFactory'
import type { GrimoireStats, ItemDefinition } from '@/types/equipment'

function g(opts: {
  aonId: number
  key?: string
  name: string
  originalName: string
  level: number
  priceGp: number
  page: number
  flavor: string
  activate: string
  frequency: string
  note: string
}): ItemDefinition {
  const grimoire: GrimoireStats = {
    activate: opts.activate,
    frequency: opts.frequency,
    note: opts.note,
  }
  return grimoireItem({
    id: `grimoire-${opts.aonId}${opts.key ? `-${opts.key}` : ''}`,
    aonId: opts.aonId,
    name: opts.name,
    originalName: opts.originalName,
    level: opts.level,
    priceGp: opts.priceGp,
    page: opts.page,
    grimoire,
    description: `${opts.flavor} Estude nas preparações diárias (só um grimório por dia, só uma pessoa). Benefícios só em magias de espaço, não truques, foco ou inatas. Ativação: ${opts.activate} (${opts.frequency}). ${opts.note}`,
  })
}

