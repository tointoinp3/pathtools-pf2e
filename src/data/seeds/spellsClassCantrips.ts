/**
 * Truques de classe que não entram nas listas de tradição:
 * hexes da bruxa, composições do bardo, truques psi únicos.
 * Remaster only.
 */
function cantrip(partial: Omit<Spell, 'rank' | 'provenance' | 'rarity' | 'focus'> & {
  rarity?: Spell['rarity']
}): Spell {
  return {
    rank: 0,
    rarity: partial.rarity ?? 'uncommon',
    provenance: { type: 'official' },
    ...partial,
  }
}

