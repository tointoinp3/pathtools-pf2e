export function localizeSpellName(originalName: string): string {
  return SPELL_NAMES_PT[originalName] ?? originalName
}

const SPELL_NAMES_PT_LOWER = new Map(
  Object.entries(SPELL_NAMES_PT).map(([en, pt]) => [en.toLowerCase(), pt]),
)

/** Troca `_English Name_` / `__English Name__` pelo nome pt-BR no corpo da magia. */
export function localizeInlineSpellNames(text: string): string {
  return text.replace(/_{1,2}([^_\n]{2,80}?)_{1,2}/g, (all, inner: string) => {
    const pt = SPELL_NAMES_PT_LOWER.get(inner.trim().toLowerCase())
    if (!pt) return all
    const wrap = all.startsWith('__') ? '__' : '_'
    return `${wrap}${pt}${wrap}`
  })
}
