export function localizeRitualName(originalName: string): string {
  return RITUAL_NAMES_PT[originalName] ?? originalName
}

const RITUAL_NAMES_PT_LOWER = new Map(
  Object.entries(RITUAL_NAMES_PT).map(([en, pt]) => [en.toLowerCase(), pt]),
)

/** Troca `_English Name_` no corpo do ritual pelo nome pt-BR. */
export function localizeInlineRitualNames(text: string): string {
  return text.replace(/_{1,2}([^_\n]{2,80}?)_{1,2}/g, (all, inner: string) => {
    const pt = RITUAL_NAMES_PT_LOWER.get(inner.trim().toLowerCase())
    if (!pt) return all
    const wrap = all.startsWith('__') ? '__' : '_'
    return `${wrap}${pt}${wrap}`
  })
}
