/** Seeds e mapas misturam ' ASCII com ’ U+2019. */
export function foldFeatApostrophe(key: string): string {
  return key.replace(/[\u2018\u2019\u201B\u0060\u00B4]/g, "'")
}

const featRecordIndex = new WeakMap<
  Record<string, string>,
  Map<string, string>
>()

function indexFeatRecord(map: Record<string, string>): Map<string, string> {
  const existing = featRecordIndex.get(map)
  if (existing) return existing
  const index = new Map<string, string>()
  for (const [k, v] of Object.entries(map)) {
    index.set(k, v)
    index.set(foldFeatApostrophe(k), v)
  }
  featRecordIndex.set(map, index)
  return index
}

/** Busca num mapa de feitos tentando apostrofe reta e curva. */
export function lookupFeatRecord(
  map: Record<string, string>,
  ...keys: Array<string | undefined | null>
): string | undefined {
  const index = indexFeatRecord(map)
  for (const key of keys) {
    if (!key) continue
    const hit = index.get(key) ?? index.get(foldFeatApostrophe(key))
    if (hit) return hit
  }
  return undefined
}

export function localizeFeatName(
  name: string,
  originalName?: string,
): string {
  const mapped =
    lookupFeatRecord(FEAT_NAMES_PT, originalName, name) ??
    lookupFeatRecord(MYTHIC_GENERAL_FEAT_NAMES_PT, originalName, name) ??
    lookupFeatRecord(GENERATED_FEAT_NAMES_PT, originalName, name) ??
    lookupFeatRecord(GENERAL_SKILL_FEAT_NAMES_PT, originalName, name) ??
    name
  return applyCatalogTokens(mapped)
}

/** True se o texto parece principalmente inglês (heurística simples). */
export function looksEnglishTitle(text: string): boolean {
  if (FEAT_NAMES_PT[text]) return true
  // títulos já em PT costumam ter acentos ou palavras comuns
  if (/[áàâãéêíóôõúçÁÀÂÃÉÊÍÓÔÕÚÇ]/.test(text)) return false
  const ptHints =
    /\b(de|do|da|dos|das|com|para|sem|golpe|postura|investida|escudo|fúria)\b/i
  if (ptHints.test(text)) return false
  return /^[A-Za-z0-9'’!().,\-\s]+$/.test(text)
}
